import { afterEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App'
import { GardenRepository } from './domain/repository'

afterEach(() => { cleanup(); localStorage.clear(); vi.restoreAllMocks() })
function notebook() {
  const repository = new GardenRepository(localStorage)
  repository.clearDemoData()
  return repository
}
it('opens a garden of saved ideas and inspects their real context and next action', async () => {
  const user = userEvent.setup(); const repository = notebook()
  const seed = repository.captureSeed({ text: 'Build my portfolio', note: 'Show decisions, not just screenshots.' })
  repository.editSeed(seed.id, { text: seed.text, note: seed.note!, nextAction: 'Write the migration story' })
  repository.captureSeed({ text: 'Try ceramics' })
  render(<App repository={repository} />)
  expect(screen.getByRole('heading', { name: 'Your ideas, growing.' })).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: /Inspect Build my portfolio/ }))
  const detail = screen.getByRole('region', { name: 'Selected idea' })
  expect(within(detail).getByText('Show decisions, not just screenshots.')).toBeInTheDocument()
  expect(within(detail).getByText('Write the migration story')).toBeInTheDocument()
  expect(within(detail).getByText('No progress recorded yet.')).toBeInTheDocument()
  await user.click(within(detail).getByRole('button', { name: 'Open idea & focus' }))
  expect(screen.getByRole('button', { name: 'Start focus' })).toBeInTheDocument()
})
it('shows recorded outcomes without claiming independent verification or automatic work', async () => {
  const repository = notebook()
  const seed = repository.captureSeed({ text: 'Field guide' })
  repository.startFocusSession(seed.id, 5)
  repository.completeFocusSession(repository.getActiveFocusSession()!.id, 'Drafted three plant profiles.')
  render(<App repository={repository} />)
  const detail = screen.getByRole('region', { name: 'Selected idea' })
  expect(within(detail).getByText('Progress recorded')).toBeInTheDocument()
  expect(within(detail).getByText('Drafted three plant profiles.')).toBeInTheDocument()
  expect(within(detail).getByText(/not independent verification/)).toBeInTheDocument()
  expect(screen.queryByText('Verified')).not.toBeInTheDocument()
  expect(screen.queryByText('Ready for review')).not.toBeInTheDocument()
})
it('marks example plants and evidence separately from real ideas', () => {
  const repository = new GardenRepository(localStorage)
  render(<App repository={repository} />)
  expect(screen.getByText(/Example ideas are illustrative/)).toBeInTheDocument()
  expect(within(screen.getByRole('region', { name: 'Selected idea' })).getByText('Example idea')).toBeInTheDocument()
})
it('captures a seed without replacing existing ideas and retains rejected drafts', async () => {
  const user = userEvent.setup(); const repository = notebook()
  repository.captureSeed({ text: 'Keep the original' })
  render(<App repository={repository} />)
  await user.click(screen.getByRole('button', { name: 'Seed a goal' }))
  expect(screen.getByLabelText('New idea')).toHaveFocus()
  fireEvent.change(screen.getByLabelText('New idea'), { target: { value: 'A new goal' } })
  await user.click(screen.getByRole('button', { name: 'Add idea' }))
  expect(repository.getState().seeds.map(seed => seed.text)).toEqual(expect.arrayContaining(['Keep the original', 'A new goal']))
  await user.click(screen.getByRole('button', { name: 'Garden' }))
  vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('Storage full') })
  fireEvent.change(screen.getByLabelText('New idea'), { target: { value: 'Keep this draft' } })
  await user.click(screen.getByRole('button', { name: 'Add idea' }))
  expect(screen.getByRole('alert')).toHaveTextContent('Storage full')
  expect(screen.getByLabelText('New idea')).toHaveValue('Keep this draft')
})
it('keeps every saved idea reachable, including an empty garden and archived search', async () => {
  const user = userEvent.setup(); const repository = notebook()
  const archived = repository.captureSeed({ text: 'Archived inspiration' })
  repository.archiveSeed(archived.id)
  render(<App repository={repository} />)
  expect(screen.getByText('Every garden starts with one idea.')).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: /Inspect Archived inspiration/ })).not.toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Search' }))
  expect(screen.getByRole('button', { name: /Open Archived inspiration/ })).toBeInTheDocument()
})
it('preserves a paused focus session and labels it honestly after reload', () => {
  const repository = notebook()
  const seed = repository.captureSeed({ text: 'Research a trip' })
  repository.startFocusSession(seed.id, 15)
  repository.pauseFocusSession(repository.getActiveFocusSession()!.id)
  const saved = repository.exportData()
  render(<App repository={new GardenRepository(localStorage)} />)
  expect(within(screen.getByRole('region', { name: 'Selected idea' })).getByText('Paused')).toBeInTheDocument()
  expect(repository.exportData()).toBe(saved)
})
it('keeps an unfinished capture across navigation and restores keyboard focus on return', async () => {
  const user = userEvent.setup(); const repository = notebook()
  repository.captureSeed({ text: 'Existing idea' })
  render(<App repository={repository} />)
  fireEvent.change(screen.getByLabelText('New idea'), { target: { value: 'Do not lose my draft' } })
  await user.click(screen.getByRole('button', { name: 'Notebook' }))
  await user.click(screen.getByRole('button', { name: 'Garden' }))
  expect(screen.getByLabelText('New idea')).toHaveValue('Do not lose my draft')
  await user.click(screen.getByRole('button', { name: 'Open idea & focus' }))
  await user.click(screen.getByRole('button', { name: /All ideas/ }))
  expect(screen.getByRole('heading', { name: 'Your ideas, growing.' })).toHaveFocus()
  expect(screen.getByLabelText('New idea')).toHaveValue('Do not lose my draft')
})
it('reveals selected details on small screens and clears only example data', async () => {
  const user = userEvent.setup(); const repository = new GardenRepository(localStorage)
  repository.captureSeed({ text: 'My own idea' })
  Object.defineProperty(window, 'matchMedia', { configurable: true, value: vi.fn(() => ({ matches: true })) })
  render(<App repository={repository} />)
  await user.click(screen.getByRole('button', { name: 'Inspect My own idea' }))
  expect(screen.getByRole('region', { name: 'Selected idea' })).toHaveFocus()
  vi.spyOn(window, 'confirm').mockReturnValue(true)
  await user.click(screen.getByRole('button', { name: 'Clear examples' }))
  expect(repository.getState().seeds.map(seed => seed.text)).toEqual(['My own idea'])
})

it('keeps the inspected plant when returning from its details or another view', async () => {
  const user = userEvent.setup(); const repository = notebook()
  repository.captureSeed({ text: 'First idea' })
  repository.captureSeed({ text: 'Second idea' })
  render(<App repository={repository} />)
  const target = screen.getAllByRole('button', { name: /^Inspect / })[1]
  const name = target.getAttribute('aria-label')!
  await user.click(target)
  await user.click(screen.getByRole('button', { name: 'Open idea & focus' }))
  await user.click(screen.getByRole('button', { name: /All ideas/ }))
  expect(screen.getByRole('button', { name })).toHaveAttribute('aria-pressed', 'true')
  await user.click(screen.getByRole('button', { name: 'Settings' }))
  await user.click(screen.getByRole('button', { name: 'Garden' }))
  expect(screen.getByRole('button', { name })).toHaveAttribute('aria-pressed', 'true')
})
